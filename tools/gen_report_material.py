def _run(p, t, size=10.5, bold=False, color=None):
    r = p.add_run(t)
    r.font.name = FONT
    r.element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    r.font.size = Pt(size)
    r.bold = bold
    if color:
        r.font.color.rgb = color
    return r


def P(t="", indent=0, size=10.5, bold=False):
    p = doc.add_paragraph()
    if indent:
        p.paragraph_format.left_indent = Cm(indent)
    _run(p, t, size, bold)
    return p


def BUL(t, indent=0.7):
    p = doc.add_paragraph(style="List Bullet")
    p.paragraph_format.left_indent = Cm(indent)
    _run(p, t)
    return p


def FORMAL(lines):
    """正式版"""
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(4)
    p.paragraph_format.space_after = Pt(2)
    _run(p, "【正式版】可直接写进报告", 10.5, True, RGBColor(0x1F, 0x3B, 0x63))
    for ln in lines:
        if ln == "":
            doc.add_paragraph().paragraph_format.space_after = Pt(1)
        else:
            q = doc.add_paragraph()
            q.paragraph_format.left_indent = Cm(0.4)
            q.paragraph_format.space_after = Pt(3)
